#!/usr/bin/env node
/**
 * Local publication mirror for marketplace + catalog + plugin manifests.
 * Does not touch DNS/TLS (EXTERNAL). Writes under dist/release-mirror/.
 *
 * Usage: node tools/scripts/publish-local-mirror.mjs
 */
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const out = join(root, "dist/release-mirror");

function run(cmd) {
  console.log(`$ ${cmd}`);
  const r = spawnSync(cmd, { cwd: root, shell: true, stdio: "inherit" });
  if (r.status !== 0) process.exit(r.status ?? 1);
}

run("npm run build -w @praxis/catalog -w @praxis/marketplace-site");

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const siteDist = join(root, "apps/marketplace-site/docs/.vitepress/dist");
if (!existsSync(siteDist)) {
  console.error("marketplace dist missing after build");
  process.exit(1);
}
cpSync(siteDist, join(out, "site"), { recursive: true });

const catalog = JSON.parse(
  readFileSync(join(root, "packages/catalog/catalog.json"), "utf8"),
);
writeFileSync(join(out, "catalog.json"), JSON.stringify(catalog, null, 2) + "\n");

const plugins = ["ba", "architect", "developer", "jira"];
for (const name of plugins) {
  const base = join(root, "plugins", name);
  const dest = join(out, "plugins", name);
  mkdirSync(dest, { recursive: true });
  for (const f of [
    ".claude-plugin/plugin.json",
    ".claude-plugin/marketplace.json",
    "package.json",
    "LICENSE",
    "README.md",
  ]) {
    const src = join(base, f);
    if (existsSync(src)) {
      mkdirSync(dirname(join(dest, f)), { recursive: true });
      cpSync(src, join(dest, f));
    }
  }
}

const manifest = {
  generatedAt: new Date().toISOString(),
  catalog,
  site: "site/",
  plugins: plugins.map((p) => `plugins/${p}/`),
  note: "Local mirror only. Domain/TLS and public CDN remain EXTERNAL BLOCKED.",
};
writeFileSync(join(out, "MANIFEST.json"), JSON.stringify(manifest, null, 2) + "\n");
writeFileSync(
  join(out, "README.md"),
  `# Praxis release mirror (local)

Generated by \`tools/scripts/publish-local-mirror.mjs\`.

Contents:
- \`site/\` — VitePress production build
- \`catalog.json\` — plugin lineup versions
- \`plugins/*/ \` — manifests / LICENSE / README for each plugin

## Next (EXTERNAL)

1. Point DNS/TLS at hosting (WBS 7.5)
2. Sync this directory to the public origin/mirror (WBS 7.3)
3. Announce channel URL for session version checks (WBS 8.5)
`,
);

console.log(JSON.stringify({ ok: true, out, plugins: catalog.plugins }, null, 2));
