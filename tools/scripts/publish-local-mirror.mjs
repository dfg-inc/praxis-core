#!/usr/bin/env node
/**
 * Local publication mirror for marketplace + catalog + installable plugins.
 * Does not touch DNS/TLS (EXTERNAL). Writes under dist/release-mirror/.
 *
 * Usage: node tools/scripts/publish-local-mirror.mjs
 */
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import {
  PLUGIN_IDS,
  buildAllPluginArtifacts,
} from "./package-plugins.mjs";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const out = join(root, "dist/release-mirror");

function run(cmd) {
  console.log(`$ ${cmd}`);
  const r = spawnSync(cmd, { cwd: root, shell: true, stdio: "inherit" });
  if (r.status !== 0) process.exit(r.status ?? 1);
}

run("npm run build -w @praxis/catalog -w @praxis/marketplace-site");

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });

const siteDist = join(root, "apps/marketplace-site/docs/.vitepress/dist");
if (!existsSync(siteDist)) {
  console.error("marketplace dist missing after build");
  process.exit(1);
}
cpSync(siteDist, join(out, "site"), { recursive: true });

const catalog = JSON.parse(
  readFileSync(join(root, "packages/catalog/catalog.json"), "utf8"),
);
writeFileSync(join(out, "catalog.json"), JSON.stringify(catalog, null, 2) + "\n");

console.log("$ stage plugin artifacts");
const staged = buildAllPluginArtifacts(out);

const manifest = {
  generatedAt: new Date().toISOString(),
  catalog,
  site: "site/",
  plugins: PLUGIN_IDS.map((p) => `plugins/${p}/`),
  packaging: Object.fromEntries(
    PLUGIN_IDS.map((id) => [
      id,
      {
        path: `plugins/${id}/`,
        requiredRefs: staged[id].refs,
        selfContained: true,
      },
    ]),
  ),
  note: "Local mirror only. Domain/TLS and public CDN remain EXTERNAL BLOCKED. Plugin dirs are installable artifacts (bundled runtime).",
};
writeFileSync(join(out, "MANIFEST.json"), JSON.stringify(manifest, null, 2) + "\n");
writeFileSync(
  join(out, "README.md"),
  `# Praxis release mirror (local)

Generated by \`tools/scripts/publish-local-mirror.mjs\`.

Contents:
- \`site/\` — VitePress production build
- \`catalog.json\` — plugin lineup versions
- \`plugins/*/\` — **self-contained** installable plugin artifacts
  - BA / Architect / Developer: Claude Code plugin surface + bundled tools/CLI
  - Jira: compiled \`dist/\` + skills + manifests

## Install a plugin artifact

\`\`\`bash
cd dist/release-mirror/plugins/ba
npm pack          # or copy the directory
# in an external project:
npm install ./path-to-tgz-or-folder
\`\`\`

Internal \`@praxis/*\` runtime deps are esbuild-bundled into the artifact — no monorepo checkout required.

## Next (EXTERNAL)

1. Point DNS/TLS at hosting (WBS 7.5)
2. Sync this directory to the public origin/mirror (WBS 7.3)
3. Announce channel URL for session version checks (WBS 8.5)
`,
);

console.log(
  JSON.stringify(
    {
      ok: true,
      out,
      plugins: catalog.plugins,
      staged: PLUGIN_IDS,
    },
    null,
    2,
  ),
);
